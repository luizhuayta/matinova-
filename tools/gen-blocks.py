#!/usr/bin/env python3
"""Generate block catalogs for PHP (copy) and Angular from cms/blocks.json."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [
    ROOT / "cms" / "blocks.json",
    ROOT / "API" / "cms" / "blocks.json",
]


def load() -> dict:
    for path in SOURCES:
        if path.is_file():
            return json.loads(path.read_text(encoding="utf-8"))
    raise SystemExit("cms/blocks.json no encontrado")


def main() -> None:
    data = load()
    pretty = json.dumps(data, ensure_ascii=False, indent=4) + "\n"
    for dest in (ROOT / "cms" / "blocks.json", ROOT / "API" / "cms" / "blocks.json"):
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(pretty, encoding="utf-8")

    ts = ROOT / "frontend" / "src" / "app" / "cms" / "block-catalog.generated.ts"
    catalog = json.dumps(data.get("blocks") or {}, ensure_ascii=False, indent=2)
    templates = json.dumps(data.get("templates") or [], ensure_ascii=False, indent=2)
    ts.write_text(
        "/* Generated by tools/gen-blocks.py — do not edit. */\n"
        "import type { BlockTypeDef, PageTemplateDef } from './block-types';\n\n"
        f"export const PAGE_TEMPLATES: PageTemplateDef[] = {templates} as PageTemplateDef[];\n\n"
        f"export const BLOCK_CATALOG: Record<string, BlockTypeDef> = {catalog} as Record<string, BlockTypeDef>;\n",
        encoding="utf-8",
    )
    print("Wrote", ts)


if __name__ == "__main__":
    main()
