-- GENERADO desde API/schema.sql por tools/build-cpanel.sh (no editar a mano).
-- Importar en una base MariaDB/MySQL vacía si no quieres esperar al auto-seed
-- del primer request. El contenido de páginas se crea solo al primer hit a /api.
-- Requisitos: utf8mb4

CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'admin',
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS pages (
  slug VARCHAR(80) NOT NULL,
  locale VARCHAR(8) NOT NULL DEFAULT 'es',
  title VARCHAR(160) NOT NULL,
  content JSON NOT NULL,
  draft LONGTEXT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  path VARCHAR(200) NOT NULL DEFAULT '',
  show_in_menu TINYINT(1) NOT NULL DEFAULT 0,
  menu_order INT NOT NULL DEFAULT 0,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (slug, locale)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS site_settings (
  locale VARCHAR(8) NOT NULL DEFAULT 'es',
  content JSON NOT NULL,
  draft LONGTEXT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (locale)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS media (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  original_name VARCHAR(255) NOT NULL,
  stored_name VARCHAR(255) NOT NULL,
  url VARCHAR(400) NOT NULL,
  mime VARCHAR(80) NOT NULL,
  size_bytes INT UNSIGNED NOT NULL,
  width INT UNSIGNED NULL,
  height INT UNSIGNED NULL,
  variants TEXT NULL,
  parent_id INT UNSIGNED NULL,
  kind VARCHAR(20) NOT NULL DEFAULT 'upload',
  original_stored VARCHAR(255) NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS media_versions (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  media_id INT UNSIGNED NOT NULL,
  stored_name VARCHAR(255) NOT NULL,
  url VARCHAR(400) NOT NULL,
  mime VARCHAR(80) NOT NULL,
  size_bytes INT UNSIGNED NOT NULL DEFAULT 0,
  width INT UNSIGNED NULL,
  height INT UNSIGNED NULL,
  reason VARCHAR(20) NOT NULL DEFAULT 'crop',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_media_versions_media (media_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS messages (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  kind VARCHAR(40) NOT NULL,
  subject VARCHAR(255) NOT NULL DEFAULT '',
  payload JSON NOT NULL,
  ticket VARCHAR(40) NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pendiente',
  mail_sent TINYINT(1) NOT NULL DEFAULT 0,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_messages_kind (kind),
  INDEX idx_messages_status (status),
  INDEX idx_messages_ticket (ticket),
  UNIQUE KEY uq_messages_ticket (ticket)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS revisions (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(80) NOT NULL,
  locale VARCHAR(8) NOT NULL DEFAULT 'es',
  author VARCHAR(80) NOT NULL DEFAULT '',
  snapshot LONGTEXT NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_rev_slug (slug),
  INDEX idx_rev_slug_locale (slug, locale)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS preview_tokens (
  token VARCHAR(64) PRIMARY KEY,
  slug VARCHAR(80) NOT NULL,
  expires_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS app_secrets (
  k VARCHAR(80) PRIMARY KEY,
  v TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS redirects (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  from_path VARCHAR(200) NOT NULL UNIQUE,
  to_path VARCHAR(200) NOT NULL,
  status SMALLINT NOT NULL DEFAULT 301,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS webhooks (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  url VARCHAR(400) NOT NULL,
  secret VARCHAR(120) NOT NULL DEFAULT '',
  events VARCHAR(255) NOT NULL DEFAULT 'publish',
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS webhook_deliveries (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  webhook_id INT UNSIGNED NOT NULL,
  event VARCHAR(80) NOT NULL,
  payload LONGTEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  last_error VARCHAR(255) NOT NULL DEFAULT '',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_wh_hook (webhook_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
